def paper_long():
    import pandas as pd
    rows = []
    for tab, cols in PAPER.items():
        for c, d in cols.items():
            for v, (bb, ss) in d["vars"].items():
                rows.append(dict(table=tab, col=c, var=v, paper_coef=bb, paper_se=ss,
                                 paper_N=d["N"], paper_adj_r2=d["adj_r2"]))
    return pd.DataFrame(rows)
